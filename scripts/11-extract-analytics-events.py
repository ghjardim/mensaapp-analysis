#!/usr/bin/env python3
"""Static census of Firebase Analytics events in blutter output (no network access).

Usage: python3 -I scripts/11-extract-analytics-events.py _work/blutter/asm/carteirinhas_mensa > docs/_evidence/analytics-events.md

For each call to `logFirebaseEvent`, the event name is the last string literal loaded before the
call (FlutterFlow passes it as the first argument). Parameter keys are taken from the literals
loaded between the previous call and this one that are not the event name. That is a heuristic,
so the table lists them as "nearby literals".
"""
import collections
import os
import re
import sys

STR = re.compile(r'^\s*// 0x[0-9a-f]+: r\d+ = "(.*)"\s*$')
CALL = '] ::logFirebaseEvent'
EVENT = re.compile(r'[A-Za-z][A-Za-z0-9_]{1,39}')


def scan(root):
    events = collections.defaultdict(list)          # name -> [(file, line)]
    nearby = collections.defaultdict(set)
    for dp, _, fs in os.walk(root):
        for f in sorted(fs):
            if not f.endswith('.dart') or f == 'analytics.dart':
                continue
            p = os.path.join(dp, f)
            window = []
            for n, line in enumerate(open(p, encoding='utf-8', errors='replace'), 1):
                m = STR.match(line)
                if m:
                    window.append(m.group(1))
                    window = window[-6:]
                elif CALL in line and ' bl ' in line:
                    cands = [w for w in window if EVENT.fullmatch(w)]
                    missed_or = not cands
                    if missed_or:
                        events['(unresolved)'].append((os.path.relpath(p, root), n))
                    if cands:
                        name = cands[-1]
                        events[name].append((os.path.relpath(p, root), n))
                        nearby[name].update(w for w in cands[:-1])
                    window = []
    return events, nearby


def main():
    root = sys.argv[1]
    events, nearby = scan(root)
    total = sum(len(v) for v in events.values())
    print(f'# Firebase Analytics events (static census of `{root}`)\n')
    print(f'{total} `logFirebaseEvent` call sites, {len(events)} distinct event names. '
          'Generated by `scripts/11-extract-analytics-events.py`. Every event also carries '
          '`user` = Firebase UID (added by the wrapper, see report 05).\n')
    print('| Event | Calls | Example site | Nearby literals (param keys?) |')
    print('|---|---|---|---|')
    for name, sites in sorted(events.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        f, n = sites[0]
        nb = ', '.join(sorted(nearby[name])[:6]) or '—'
        print(f'| `{name}` | {len(sites)} | `{f}:{n}` | {nb} |')


if __name__ == '__main__':
    main()
