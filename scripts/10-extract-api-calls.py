#!/usr/bin/env python3
"""Static extraction of FlutterFlow API calls from blutter output (no network access).

Usage: python3 -I scripts/10-extract-api-calls.py _work/blutter/asm/carteirinhas_mensa/backend/api_requests/api_calls.dart > docs/_evidence/api-calls.md

For each `class XxxCall` it lists: call name, URL pieces (host/path literals), body JSON keys,
other string literals (header/query keys), the ApiCallType / BodyType enum object addresses,
and the source line in the blutter file. HTTP method is NOT resolved here (see investigation log).
"""
import re
import sys

STR = re.compile(r'^\s*// 0x[0-9a-f]+: r\d+ = "(.*)"\s*$')
CLASS = re.compile(r'^class (\w+Call) extends')
ENUM = re.compile(r'Obj!(ApiCallType|BodyType)@([0-9a-f]+)')
BODYKEY = re.compile(r'\\"(\w+)\\":')
MAKE = 'makeApiCall()'


def parse(path):
    calls, cur = [], None
    for n, line in enumerate(open(path, encoding='utf-8', errors='replace'), 1):
        m = CLASS.match(line)
        if m:
            cur = dict(cls=m.group(1), line=n, strs=[], enums={}, made=False)
            calls.append(cur)
            continue
        if cur is None:
            continue
        m = STR.match(line)
        if m:
            cur['strs'].append(m.group(1))
        for kind, addr in ENUM.findall(line):
            cur['enums'].setdefault(kind, addr)
            if kind == 'ApiCallType' and 'name' not in cur:
                # FlutterFlow passes callName in the register loaded just before the ApiCallType
                cur['name'] = cur['strs'][-1] if cur['strs'] else ''
        if MAKE in line:
            cur['made'] = True
    return calls


def summarize(c):
    s = c['strs']
    urls = [x for x in s if x.startswith('http')]
    paths = [x for x in s if x.startswith('/') and not x.startswith('//')]
    body = []
    for x in s:
        body += [k for k in BODYKEY.findall(x) if k not in body]
    hdr = [x for x in ('Authorization', 'Content-Type', 'Content-type') if x in s]
    other = [x for x in s if x not in urls + paths + hdr and '\\"' not in x and not x.startswith('$.')
             and x not in ('Bearer ', 'application/json', '\\', '\\\\', '\\n', '\\t', '"', '\\"')]
    name = c.get('name', '')
    other = [x for x in other if x != name and re.fullmatch(r'[A-Za-z_][\w-]*', x)]
    jsonpaths = sorted({x for x in s if x.startswith('$.')})
    return name, urls, paths, body, hdr, other, jsonpaths


def main():
    allc = parse(sys.argv[1])
    calls = [c for c in allc if c['made']]
    skipped = [c['cls'] for c in allc if not c['made']]
    print(f'# API calls extracted from `{sys.argv[1]}`\n')
    print(f'{len(calls)} classes reach `ApiManager.makeApiCall`. Generated by '
          '`scripts/10-extract-api-calls.py` (static, no network). Line = line in the blutter file.\n')
    print('| # | Class (line) | callName | URL / path literals | Body JSON keys | Other keys (query/path params) | Auth | ApiCallType obj |')
    print('|---|---|---|---|---|---|---|---|')
    for i, c in enumerate(calls, 1):
        name, urls, paths, body, hdr, other, _ = summarize(c)
        auth = 'Bearer' if 'Authorization' in hdr else '—'
        print(f"| {i} | `{c['cls']}` ({c['line']}) | `{name}` | {'<br>'.join(f'`{u}`' for u in urls + paths)} | "
              f"{', '.join(body) or '—'} | {', '.join(other) or '—'} | {auth} | `{c['enums'].get('ApiCallType', '?')}` |")
    if skipped:
        print(f"\nClasses without a `makeApiCall` (helpers/response wrappers): {', '.join(f'`{x}`' for x in skipped)}")
    print('\n## Response fields read (JSONPath literals)\n')
    for c in calls:
        jp = summarize(c)[6]
        if jp:
            print(f"- `{c['cls']}`: {', '.join(f'`{j}`' for j in jp)}")


if __name__ == '__main__':
    main()
