#!/usr/bin/env python3
"""Static extraction of FlutterFlow go_router routes from blutter output (no network access).

Usage: python3 -I scripts/12-extract-routes.py _work/blutter/asm/carteirinhas_mensa/flutter_flow/nav/nav.dart > docs/_evidence/routes.md

FlutterFlow builds each route as FFRoute(name: field_7, path: field_b, requireAuth: field_f,
builder: closure). The builder closure's body shows which page widget is built and which
parameters it reads via FFParameters.getParam(). These parameters can be supplied by a deep link's
query string.
"""
import re
import sys

REG_STR = re.compile(r'// 0x[0-9a-f]+: (r\d+) = "(.*)"\s*$')
REG_BOOL = re.compile(r'// 0x[0-9a-f]+: (r\d+) = (true|false)\s*$')
STORE = re.compile(r'StoreField: r\d+->field_(7|b|f) = (r\d+)')
CLOSURE_REF = re.compile(r'AnonymousClosure: static \((0x[0-9a-f]+)\), in \[[^]]+\] ::createRouter')
CLOSURE_DEF = re.compile(r'^\s+\[closure\] static \w+ <anonymous closure>\(dynamic, BuildContext, FFParameters\)')
ADDR = re.compile(r'// \*\* addr: (0x[0-9a-f]+)')
ALLOC_WIDGET = re.compile(r'Allocate(\w+Widget)Stub')


def parse(path):
    lines = open(path, encoding='utf-8', errors='replace').read().splitlines()
    routes, regs, cur = [], {}, None
    for n, line in enumerate(lines, 1):
        if 'AllocateFFRouteStub' in line:
            cur = dict(line=n, name=None, path=None, auth=None, closure=None)
            routes.append(cur)
            continue
        m = REG_STR.search(line)
        if m:
            regs[m.group(1)] = m.group(2)
        m = REG_BOOL.search(line)
        if m:
            regs[m.group(1)] = m.group(2)
        if cur is None:
            continue
        m = STORE.search(line)
        if m:
            key = {'7': 'name', 'b': 'path', 'f': 'auth'}[m.group(1)]
            if cur[key] is None:
                cur[key] = regs.get(m.group(2), '?')
        m = CLOSURE_REF.search(line)
        if m and cur['closure'] is None:
            cur['closure'] = m.group(1)
    # builder closures: widget + getParam names
    builders, i = {}, 0
    while i < len(lines):
        if CLOSURE_DEF.match(lines[i]):
            addr = ADDR.search(lines[i + 1]).group(1) if ADDR.search(lines[i + 1]) else None
            j, params, widget, last = i + 1, [], None, None
            while j < len(lines) and not lines[j].startswith('  }'):
                m = REG_STR.search(lines[j])
                if m:
                    last = m.group(2)
                if 'FFParameters::getParam' in lines[j] and last and last not in params:
                    params.append(last)
                m = ALLOC_WIDGET.search(lines[j])
                if m and widget is None:
                    widget = m.group(1)
                j += 1
            builders[addr] = (widget, params)
            i = j
        i += 1
    return routes, builders


def main():
    routes, builders = parse(sys.argv[1])
    print(f'# go_router routes (static extraction of `{sys.argv[1]}`)\n')
    print(f'{len(routes)} `FFRoute`s. Generated by `scripts/12-extract-routes.py`. Deep link form: '
          '`carteirinhasmensa://carteirinhasmensa.com/<path>?<param>=…`. Params are the names read with '
          '`getParam` in the builder closure.\n')
    print('| # | Name | Path | requireAuth | Widget | Params (getParam) | nav.dart line |')
    print('|---|---|---|---|---|---|---|')
    for k, r in enumerate(routes, 1):
        w, p = builders.get(r['closure'], (None, []))
        print(f"| {k} | `{r['name']}` | `{r['path']}` | {r['auth']} | `{w or '?'}` | "
              f"{', '.join(f'`{x}`' for x in p) or '—'} | {r['line']} |")


if __name__ == '__main__':
    main()
